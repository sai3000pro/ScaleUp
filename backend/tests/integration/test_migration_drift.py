"""A generated migration diff against the migrated schema proposes nothing."""

from __future__ import annotations

from pathlib import Path

import pytest
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from alembic import command

BACKEND = Path(__file__).resolve().parents[2]


# @spec OPS-MIGRATE-006
def test_models_match_the_migrated_schema() -> None:
    config = Config(str(BACKEND / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND / "alembic"))
    try:
        command.check(config)
    except AutogenerateDiffsDetected as drift:
        pytest.fail(f"alembic check found drift between models and migrations:\n{drift}")
