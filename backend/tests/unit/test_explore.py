"""Explore: search ranking, citation discipline, and the guided walk's order.

Everything here is the pure half -- no database, no Chroma, no key. The parts
that need a live index are exercised in `tests/integration/test_explore_api.py`;
what is pinned here is the logic that decides *what an answer is allowed to say*,
which is where the damage lives.
"""

from __future__ import annotations

import uuid

from app.ingestion.summarise import NodeBrief, render_briefs
from app.llm.base import LLMRole
from app.llm.fake_provider import FakeLLMClient
from app.models import Chunk, SkillNode
from app.services.path_service import contracted_prereqs
